#!/usr/bin/env python3
"""ER-003: write .extern size hints for every symbol splat's asm reaches through $gp.

ee-as 2.9 has no %gp_rel operator, so splat runs with use_gp_rel_macro(_nonmatching): False and writes
gp-relative accesses as gas macros (`lw $2, (D_0035B810)`). Under -G8 the assembler turns a macro into one
gp-relative instruction only when it knows the symbol is small: for a symbol not defined in the same file
that means `.extern sym, size` with size <= 8 (gas/config/tc-mips.c nopic_need_relax). spimdisasm tags each
such line `/* gp_rel: (SYM) */` or `(SYM + 0x4)`; this collects the symbols and writes one `.extern` each.
The size 4 is only an assembler hint (any value <= the -G size gives the same instruction).

Usage: python -I tools/gen_gp_externs.py <asm dir> <out.inc>
"""
import re
import sys
from pathlib import Path

TAG = re.compile(r"/\* gp_rel: \(\s*([A-Za-z_.$][A-Za-z0-9_.$]*)")


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    asm_dir, out = Path(sys.argv[1]), Path(sys.argv[2])
    syms: set[str] = set()
    for f in sorted(asm_dir.rglob("*.s")):
        syms.update(TAG.findall(f.read_text(encoding="utf-8", errors="replace")))
    lines = ["# Generated by tools/gen_gp_externs.py from the split; do not edit.\n"]
    lines += [f".extern {s}, 4\n" for s in sorted(syms)]
    text = "".join(lines)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
    print(f"{out}: {len(syms)} symbols")


if __name__ == "__main__":
    main()
