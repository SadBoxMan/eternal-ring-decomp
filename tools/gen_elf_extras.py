#!/usr/bin/env python3
"""ER-003: write asm for the ELF sections of SLUS_200.15 that lie outside the load image.

splat splits the PT_LOAD bytes only. The whole-file SHA-1 also needs the sections the linker writes after
the load image (docs/toolchain.md 2.2): the DVP overlay sections that ee-dvp-as made for the four VU1 microprograms (.DVP.ovlytab, .DVP.ovlystrtab, .DVP.overlay.*). ee-dvp-as is
not built (ER-012), so their bytes are taken from the original ELF as data, the same way splat keeps data.
bfd sets their section types by name (bfd/elf32-mips.c _bfd_mips_elf_fake_sections). .reginfo and
.shstrtab are made by the linker; the empty .vutext / .vubss are in src/elf_layout.s (no game bytes).

Bytes are written with .byte only: MIPS gas auto-aligns .word to 4, which would raise the sections'
alignment above the original 1 and move their file offsets. The output is game data (gitignored asm/).

Usage: python -I tools/gen_elf_extras.py <SLUS_200.15> <out.s>
"""
import struct
import sys
from pathlib import Path

SHF_WRITE, SHF_ALLOC, SHF_EXECINSTR = 1, 2, 4
SHT_NOBITS = 8
WANTED_PREFIXES = (".DVP.",)


def sections(elf: bytes):
    e_shoff, = struct.unpack_from("<I", elf, 0x20)
    e_shentsize, e_shnum, e_shstrndx = struct.unpack_from("<HHH", elf, 0x2E)
    hdrs = [struct.unpack_from("<10I", elf, e_shoff + i * e_shentsize) for i in range(e_shnum)]
    stroff = hdrs[e_shstrndx][4]
    for h in hdrs[1:]:
        name_off = stroff + h[0]
        name = elf[name_off:elf.index(b"\0", name_off)].decode("ascii")
        yield name, h


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    elf = Path(sys.argv[1]).read_bytes()
    out = Path(sys.argv[2])
    w = ["# Generated by tools/gen_elf_extras.py from the original ELF; do not edit. Game data: never commit.\n"]
    for name, (_n, sh_type, sh_flags, _addr, off, size, _link, _info, align, _es) in sections(elf):
        if not name.startswith(WANTED_PREFIXES):
            continue
        flags = ("a" if sh_flags & SHF_ALLOC else "") + ("w" if sh_flags & SHF_WRITE else "") \
            + ("x" if sh_flags & SHF_EXECINSTR else "")
        kind = ",@nobits" if sh_type == SHT_NOBITS else ""
        w.append(f'\n.section {name},"{flags}"{kind}\n')
        if align > 1:
            w.append(f".align {align.bit_length() - 1}\n")
        if sh_type == SHT_NOBITS:
            if size:
                w.append(f".space {size:#x}\n")
            continue
        data = elf[off:off + size]
        for i in range(0, len(data), 16):
            w.append("    .byte " + ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + "\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(w), encoding="utf-8", newline="\n")
    print(f"{out}: written")


if __name__ == "__main__":
    main()
