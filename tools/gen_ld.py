#!/usr/bin/env python3
"""ER-003: write the ee-ld linker script for SLUS_200.15 from splat's generated script.

splat's script puts the whole segment into one output section (.main). The game ELF has SCE's standard EE
layout (app.cmd form, docs/toolchain.md 2.2/2.3): one output section per input section kind, each 128-byte
aligned, the VU sections where the SDK script puts them, gp = .lit4 start + 0x7FF0. This keeps splat's
object order inside each section (so yaml changes flow through) and rewrites the frame:

  .text .vutext .reginfo .data .vudata .rodata .lit4 .sdata .sbss .bss .vubss .DVP.ovlytab .DVP.ovlystrtab
  then the four .DVP.overlay.* sections (non-alloc orphans, address 0) and .shstrtab.

splat's `pad` entries (`. += N;`) and subsegments named pad_* (used where splat's pad type cannot go, in
the NOBITS range) are dropped: the 128-byte section alignment makes the same fill.
.reginfo: bfd marks every input .reginfo SEC_LINK_ONCE | SEC_LINK_DUPLICATES_SAME_SIZE
(bfd/elf32-mips.c, _bfd_mips_elf_section_from_shdr), so ld keeps only the first object's copy and
discards the rest. The game's ri_gprmask (0xB00001FE) is exactly crt0's registers (docs/toolchain.md 2.3):
crt0 was first on SCE's link line. The Makefile passes crt0's object first for the same result.
The splat undefined_*_auto files are appended (ee-ld 2.9 takes one -T script).

src/elf_layout.s (LAYOUT_O) goes first in each output section: it holds the empty .vutext / .vubss and
empty input sections that carry the original section alignments.

Usage: python -I tools/gen_ld.py <splat.ld> <out.ld> [extra.ld ...]
"""
import re
import sys
from pathlib import Path

GROUP = re.compile(r"^\s*main_(\w+?)_START = \.;")
LAYOUT_O = "build/src/elf_layout.o"
LAYOUT_SECTIONS = {".text", ".vutext", ".data", ".vudata", ".rodata", ".sdata", ".sbss", ".bss", ".vubss"}
END = re.compile(r"^\s*main_(\w+?)_END = \.;")
OBJ = re.compile(r"^\s*(build/\S+\.o)\((.*)\);\s*$")

# output section -> (address expression, extra inputs after splat's objects)
FRAME = [
    (".text", "0x00100000", ""),
    (".vutext", "", "*(.vutext)"),
    (".reginfo", "", "*(.reginfo)"),  # link-once: the first object's (crt0's) copy
    (".data", "ALIGN(128)", ""),
    (".vudata", "ALIGN(16)", "*(.vudata)"),
    (".rodata", "ALIGN(128)", ""),
    (".lit4", "ALIGN(128)", ""),
    (".sdata", "ALIGN(128)", ""),
    (".sbss", "ALIGN(128)", "*(.scommon)"),
    (".bss", "ALIGN(128)", "*(COMMON)"),
    (".vubss", "", "*(.vubss)"),
    (".DVP.ovlytab", "", "*(.DVP.ovlytab)"),
    (".DVP.ovlystrtab", "", "*(.DVP.ovlystrtab)"),
]


def parse_splat(path: Path) -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {}
    cur = None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = GROUP.match(line)
        if m:
            cur = "." + m[1].lower()
            groups.setdefault(cur, [])
            continue
        if END.match(line):
            cur = None
            continue
        m = OBJ.match(line)
        if m and cur is not None:
            obj, spec = m[1], m[2]
            if Path(obj).name.startswith("pad_"):
                continue
            # keep only the input-section kind of this group; drop COMMON/.scommon (added once, below)
            kinds = [k for k in spec.split() if k not in ("COMMON", ".scommon")]
            groups[cur].append(f"{obj}({' '.join(kinds)})")
    return groups


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    splat_ld, out = Path(sys.argv[1]), Path(sys.argv[2])
    extras = [Path(p) for p in sys.argv[3:]]
    groups = parse_splat(splat_ld)
    known = {name for name, _, _ in FRAME}
    unknown = set(groups) - known
    if unknown:
        sys.exit(f"gen_ld: splat groups with no output section: {sorted(unknown)}")

    w = ["/* Generated by tools/gen_ld.py from splat's script; do not edit. */",
         'OUTPUT_FORMAT("elf32-littlemips")',
         "ENTRY(func_00100008)",
         "PHDRS",
         "{",
         "    load PT_LOAD FLAGS(7);",
         "}",
         "SECTIONS",
         "{"]
    for name, addr, tail in FRAME:
        if name == ".lit4":
            w.append("    _gp = ALIGN(128) + 0x7FF0;")
        head = f"    {name} {addr} :" if addr else f"    {name} :"
        w.append(head)
        w.append("    {")
        if name in LAYOUT_SECTIONS:
            w.append(f"        {LAYOUT_O}({name})")
        for entry in groups.get(name, []):
            w.append(f"        {entry}")
        if tail:
            w.append(f"        {tail}")
        w.append("    }" + (" :load" if name == ".text" else ""))
    w += ["    /DISCARD/ :",
          "    {",
          "        *(.mdebug) *(.gptab.*) *(.comment) *(.pdr)",
          "    }",
          "}",
          ""]
    for extra in extras:
        w.append(f"/* from {extra.as_posix()} */")
        w += [l for l in extra.read_text(encoding="utf-8").splitlines()]
    text = "\n".join(w) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
